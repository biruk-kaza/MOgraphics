import cueData from '../data/voiceover-cues.json';
import envelopeData from '../data/envelope.json';
import {clamp, progress} from './frameMath';
import {easeInOutCubic, easeOutCubic} from './easing';

export type Confidence = 'detected' | 'snapped' | 'interpolated' | 'estimated' | 'manual' | 'verified';
export type Emphasis = 'none' | 'minor' | 'major';

export interface WordCue {
  text: string;
  startFrame: number; // inclusive
  endFrame: number; // exclusive
  peakFrame: number; // loudest frame inside the word
  emphasis: Emphasis;
  confidence: Confidence;
}
export interface PhraseCue { startWord: number; endWord: number; startFrame: number; endFrame: number }
export interface LineCue { index: number; text: string; startFrame: number; endFrame: number; phrases: PhraseCue[]; words: WordCue[] }
export interface CueSheet {
  fps: number;
  audioFile: string | null;
  totalFrames: number;
  timingMethod: string;
  lines: LineCue[];
}

/** Single source of truth for timing (generated by scripts/build-cues.mjs). */
export const cues = cueData as unknown as CueSheet;
const energy = (envelopeData as {values: number[]}).values;

/** 1-based line, 0-based word — mirrors how the brief numbers things. */
export const lineAt = (line: number): LineCue => cues.lines[line - 1];
export const wordAt = (line: number, word: number): WordCue => cues.lines[line - 1].words[word];

export const energyAt = (frame: number) => energy[clamp(Math.round(frame), 0, energy.length - 1)] ?? 0;

/** Which line/word is being spoken at `frame` (or the most recent one during pauses). */
export function getActiveCue(frame: number, lines: LineCue[] = cues.lines) {
  let lineIndex = -1;
  for (let i = 0; i < lines.length; i++) if (frame >= lines[i].startFrame) lineIndex = i;
  const line = lineIndex >= 0 ? lines[lineIndex] : null;
  let wordIndex = -1;
  if (line) for (let i = 0; i < line.words.length; i++) if (frame >= line.words[i].startFrame) wordIndex = i;
  const word = line && wordIndex >= 0 ? line.words[wordIndex] : null;
  const speaking = !!word && frame < word.endFrame;
  return {line, lineIndex, word, wordIndex, speaking};
}

/** entered: 0→1 as the word is revealed; spoken: 0→1 across its spoken duration; active: currently being said. */
export function getWordProgress(frame: number, word: WordCue, ramp = 10, lead = 1) {
  const entered = progress(frame, word.startFrame - lead, word.startFrame - lead + ramp);
  const spoken = progress(frame, word.startFrame, word.endFrame);
  const active = frame >= word.startFrame && frame < word.endFrame;
  return {entered, spoken, active, done: frame >= word.endFrame};
}

export function getLineProgress(frame: number, line: LineCue) {
  return {
    entered: progress(frame, line.startFrame, line.startFrame + 12),
    spoken: progress(frame, line.startFrame, line.endFrame),
    active: frame >= line.startFrame && frame < line.endFrame,
    done: frame >= line.endFrame,
  };
}

/** Frame at which an emphasis reaction should fire: the vocal peak for major words, the onset otherwise. */
export const triggerFrame = (w: WordCue) => (w.emphasis === 'major' ? w.peakFrame : w.startFrame);

/** Decaying pulse (1 at trigger → 0) with a 2-frame attack. */
export function getEmphasisState(frame: number, word: WordCue, decay = 12) {
  const t = frame - triggerFrame(word);
  if (t < 0) return {pulse: 0, level: word.emphasis, sinceTrigger: t};
  const attack = clamp(t / 2);
  const pulse = attack * Math.exp(-t / decay);
  return {pulse, level: word.emphasis, sinceTrigger: t};
}

export function getTransitionProgress(frame: number, start: number, end: number, ease: (t: number) => number = easeInOutCubic) {
  return ease(progress(frame, start, end));
}

/** 0→1→0 envelope: rises over `rise` frames after `start`, falls over `fall` frames. */
export function bump(frame: number, start: number, rise: number, fall: number) {
  if (frame < start) return 0;
  if (frame < start + rise) return easeOutCubic((frame - start) / rise);
  return 1 - easeInOutCubic(progress(frame, start + rise, start + rise + fall));
}
