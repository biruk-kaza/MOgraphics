// Shared audio helpers (ffmpeg/ffprobe based). No third-party npm dependencies.
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const AUDIO_EXT = ['.wav', '.mp3', '.m4a', '.aac', '.ogg', '.flac', '.opus'];
export const SAMPLE_RATE = 16000;
export const HOP_MS = 10;

export function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, {maxBuffer: 1024 * 1024 * 1024, ...opts});
  if (r.error) throw new Error(`Cannot run "${cmd}": ${r.error.message}. Is it installed?`);
  if (r.status !== 0) throw new Error(`${cmd} failed (${r.status}): ${(r.stderr || '').toString().slice(0, 1500)}`);
  return r;
}

export function probeAudio(file) {
  const r = run('ffprobe', ['-v', 'error', '-show_streams', '-show_format', '-of', 'json', file]);
  const j = JSON.parse(r.stdout.toString());
  const a = (j.streams || []).find((s) => s.codec_type === 'audio');
  if (!a) throw new Error(`No audio stream in ${file}`);
  return {
    codec: a.codec_name,
    sampleRate: Number(a.sample_rate),
    channels: Number(a.channels),
    durationSeconds: Number(j.format.duration || a.duration),
  };
}

/** Decode to mono 16-bit PCM at 16 kHz and return Float32 samples in [-1, 1]. */
export function decodeMono(file, sampleRate = SAMPLE_RATE) {
  const r = run('ffmpeg', ['-v', 'error', '-i', file, '-vn', '-ac', '1', '-ar', String(sampleRate), '-f', 's16le', '-']);
  const buf = r.stdout;
  const n = Math.floor(buf.length / 2);
  const out = new Float32Array(n);
  for (let i = 0; i < n; i++) out[i] = buf.readInt16LE(i * 2) / 32768;
  return out;
}

/** Short-time RMS level in dBFS, one value per hop (default 10 ms, 20 ms window), lightly smoothed. */
export function envelopeDb(samples, sampleRate = SAMPLE_RATE, hopMs = HOP_MS) {
  const hop = Math.round((sampleRate * hopMs) / 1000);
  const win = hop * 2;
  const n = Math.max(1, Math.floor(samples.length / hop));
  const raw = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    let s = 0;
    const a = i * hop;
    let c = 0;
    for (let j = 0; j < win && a + j < samples.length; j++, c++) s += samples[a + j] * samples[a + j];
    raw[i] = 20 * Math.log10(Math.sqrt(s / Math.max(1, c)) + 1e-6);
  }
  const db = new Float32Array(n);
  for (let i = 0; i < n; i++) db[i] = (raw[Math.max(0, i - 1)] + raw[i] + raw[Math.min(n - 1, i + 1)]) / 3;
  return {db, hopSeconds: hop / sampleRate};
}

export function listAudioCandidates() {
  const dirs = ['public/audio', 'public', 'assets', 'input', 'audio', '.'].map((d) => path.join(ROOT, d));
  const seen = new Set();
  const found = [];
  for (const d of dirs) {
    if (!fs.existsSync(d)) continue;
    for (const name of fs.readdirSync(d)) {
      const p = path.join(d, name);
      if (!fs.statSync(p).isFile()) continue;
      if (!AUDIO_EXT.includes(path.extname(name).toLowerCase())) continue;
      if (p.includes(`${path.sep}output${path.sep}`)) continue;
      if (/\.synced\.wav$/i.test(name)) continue; // generated by build-cues
      if (!seen.has(p)) { seen.add(p); found.push(p); }
    }
  }
  return found;
}

/** Pick the narration track. Honors $VOICEOVER, then name hints, then closeness to the ~17 s brief. */
export function findVoiceover(log = console.log) {
  if (process.env.VOICEOVER) {
    const p = path.resolve(ROOT, process.env.VOICEOVER);
    if (!fs.existsSync(p)) throw new Error(`$VOICEOVER points to a missing file: ${p}`);
    return p;
  }
  const cands = listAudioCandidates();
  if (cands.length === 0) return null;
  const rows = cands.map((p) => ({p, ...probeAudio(p)}));
  rows.forEach((r) => log(`  candidate: ${path.relative(ROOT, r.p)}  ${r.durationSeconds.toFixed(2)}s ${r.sampleRate}Hz ch=${r.channels}`));
  if (rows.length === 1) return rows[0].p;
  const hinted = rows.filter((r) => /voice|narrat|\bvo\b|amharic|speech|vocal/i.test(path.basename(r.p)));
  const pool = hinted.length ? hinted : rows;
  pool.sort((a, b) => Math.abs(a.durationSeconds - 17) - Math.abs(b.durationSeconds - 17));
  log(`  multiple audio files found; chose "${path.relative(ROOT, pool[0].p)}" (name hint, then closeness to 17 s). Set VOICEOVER=<path> to override.`);
  return pool[0].p;
}
